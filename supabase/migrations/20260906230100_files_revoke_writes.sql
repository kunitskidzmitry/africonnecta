-- Гранты на запись в public.files отбираются у клиентских ролей.
--
-- Миграция 20260906230000 сняла политики insert/update/delete. При включённом RLS
-- этого достаточно: отсутствие политики — запрет. Но гранты table-level всё ещё
-- разрешали INSERT/UPDATE/DELETE на уровне Postgres, и единственным замком оставался
-- RLS. Если политика когда-нибудь ошибётся или функцию security definer кто-то
-- напишет с правами вызывающего неверно — клиент снова сможет писать в files
-- мимо проверки сигнатуры. Два замка дешевле одной дыры: revoke здесь, политики
-- там.
--
-- service_role гранты не касаются: эта роль обходит и RLS, и ей они не нужны.

revoke insert, update, delete on public.files from anon, authenticated;
