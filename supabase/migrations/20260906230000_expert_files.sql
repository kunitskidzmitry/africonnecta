-- Файлы эксперта: фотография и CV (§7, строка «Загрузка файлов»).
--
-- Главное решение этой миграции: клиентские роли в бакет и в public.files не пишут вовсе.
-- Только читают.
--
-- Причина не в осторожности, а в том, что иначе проверку по сигнатуре нельзя навязать.
-- §7 требует проверять MIME по содержимому файла, а не по расширению; проверить
-- содержимое может только тот, у кого байты на руках, то есть наш сервер. Но пока
-- запись разрешена роли authenticated, у браузера ровно те же права: можно не звать
-- наш обработчик и положить в свою папку что угодно, объявив это image/jpeg. Проверка
-- превращается в вежливую просьбу, а критерий M1 «файлы проверяются по сигнатуре» —
-- в проверку, которую любой обходит одним запросом.
--
-- Отличить наш сервер от браузера можно только тем, чего у браузера нет, — служебным
-- ключом. Его появление здесь предусмотрено заранее (.env.example: «переменная появится
-- только когда возникнет операция, которую иначе не сделать»), разбор в ADR-0008.
--
-- Побочная выгода: на storage.objects клиентам не нужна ни одна политика записи,
-- и «можно писать в свою папку» перестаёт быть частью модели угроз.

-- ---------------------------------------------------------------------------
-- Бакет
--
-- Один на оба вида файла, а не два. Вид определяется вторым сегментом пути
-- (<user_id>/photo/... и <user_id>/cv/...), и этого достаточно: права на чтение
-- всё равно решает строка в public.files, а не бакет.
--
-- Приватный. Публичный бакет отдавал бы фотографию по угадываемому адресу мимо
-- всякой политики, а видимость профиля — это как раз то, что политика решает:
-- у скрытого профиля и черновика фотография не показывается никому.
--
-- Лимит и список типов дублируют проверку в обработчике. Это не избыточность:
-- обработчик отвечает на вопрос «что за файл», а бакет — «сколько байт хранилище
-- согласно принять», и второе должно держаться без первого.
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'expert-files',
  'expert-files',
  false,
  5242880,
  array['image/jpeg', 'image/png', 'application/pdf']
)
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

-- ---------------------------------------------------------------------------
-- Вид файла
--
-- Колонки в §4.7 нет, и обойтись без неё не получается: политика ниже обязана
-- различать фотографию и CV, а спросить об этом больше нечего. Взять вид из пути
-- (`.../cv/...`) можно, но тогда правило доступа держится на разборе текста, и опечатка
-- в сборке пути становится дырой в правах, а не сломанной ссылкой.
--
-- Проверка связывает путь, владельца и вид: <user_id>/<kind>/<...>. Она в базе,
-- а не только в обработчике, потому что политика на storage.objects сопоставляет
-- объект со строкой именно по этому пути. Ошибка в сборке падает при вставке, а не
-- превращается в файл, который видно не тому.
-- ---------------------------------------------------------------------------

create type public.file_kind as enum ('photo', 'cv');

alter table public.files add column kind public.file_kind;

update public.files
   set kind = (case when storage_key like '%/cv/%' then 'cv' else 'photo' end)::public.file_kind
 where kind is null;

alter table public.files alter column kind set not null;

alter table public.files
  add constraint files_key_matches_owner_and_kind
  check (storage_key like owner_user_id::text || '/' || kind::text || '/%');

-- ---------------------------------------------------------------------------
-- Кто видит строку файла
--
-- Асимметрия фотографии и CV взята из §8.1 и §7. Фотография — часть витрины:
-- её видит каждый, кому виден профиль. CV — вложение к контактам, и §7 называет
-- его выкачивание главным риском: его получает только институция, уже потратившая
-- квоту на раскрытие контактов этого эксперта.
--
-- Видимость профиля здесь не переписана заново: `exists (select 1 from experts ...)`
-- читает experts под политикой вызывающего, поэтому у скрытого профиля и черновика
-- строка фотографии не находится сама собой. Так правило видимости остаётся в одном
-- месте (experts_select_visible), но появляется зависимость: политика, разрешившая
-- лишнее в experts, разрешит лишнее и здесь. От этого стоят тесты
-- tests/integration/files.test.ts — они спрашивают именно про скрытый профиль
-- и черновик.
--
-- Ветви фотографии и CV устроены по-разному, и это следствие §7, а не небрежность.
-- Фотография сверяется по факту привязки (`e.photo_file_id = files.id`) — самый точный
-- вопрос из возможных. Для CV так нельзя: колонка experts.cv_file_id отобрана
-- у клиентских ролей на уровне грантов, и выражение политики, её читающее, падает
-- с «permission denied for table experts» — причём не только в самом запросе, но и
-- в любом триггере, который прочитает files. Поэтому CV опознаётся по виду файла,
-- а право — по строке раскрытия для того же эксперта.
--
-- Практическая разница: институция, потратившая квоту, увидит и прежние CV этого
-- эксперта, если они остались в хранилище, а не только текущее. Это те же
-- персональные данные того же человека, полученные по тому же праву.
--
-- scan_status <> 'infected' — единственное, что связывает эти политики со сканером.
-- Сканера в Фазе 1 нет и статус остаётся 'pending' (ADR-0008), то есть условие пока
-- не отсекает ничего. Замок врезан заранее: когда сканер появится, его работа сводится
-- к простановке статуса, а не к правке политик во всех таблицах сразу.
-- ---------------------------------------------------------------------------

drop policy files_select_own on public.files;

create policy files_select_visible on public.files
  for select
  using (
    scan_status <> 'infected'
    and (
      owner_user_id = (select auth.uid())
      or (select public.is_admin())
      or (
        kind = 'photo'
        and exists (
          select 1 from public.experts e where e.photo_file_id = files.id
        )
      )
      or (
        kind = 'cv'
        and exists (
          select 1
          from public.experts e
          join public.contact_disclosures d on d.expert_id = e.id
          where e.user_id = files.owner_user_id
            and d.institution_id = (select public.current_institution_id())
        )
      )
    )
  );

-- Запись строки — только служебным ключом (см. заголовок). Политики insert, update
-- и delete для клиентских ролей отсутствуют намеренно: при включённом RLS отсутствие
-- политики означает запрет, и это нужный ответ. Гранты на запись отзываются отдельно
-- (миграция 20260906230100): иначе критерий M1 держался бы на одном замке.
drop policy files_insert_own on public.files;

comment on table public.files is
  'Файл публикуется только при scan_status = clean (§9). MIME проверяется по сигнатуре '
  'содержимого, а не по расширению. Строки создаёт только сервер служебным ключом: '
  'иначе проверку сигнатуры обходит любой клиент (ADR-0008).';

-- ---------------------------------------------------------------------------
-- Кто видит сам объект
--
-- Право на объект выведено из права на строку, а не написано во второй раз:
-- `exists (select 1 from public.files ...)` проходит через политику files_select_visible,
-- поэтому подписать ссылку хранилище позволит ровно тому, кому видна строка.
--
-- Иначе условие пришлось бы держать в двух местах, и разъехались бы они молча:
-- строка видна, объекта нет — сломанная картинка; объект виден, строки нет — утечка.
-- Объект без строки не читается вовсе, и это тоже нужное поведение: файл, загруженный
-- в обход обработчика, остаётся мусором, а не превращается в достижимое содержимое.
--
-- Политик записи нет ни одной. Служебный ключ RLS не проверяет, ему они не нужны.
-- ---------------------------------------------------------------------------

create policy expert_files_select on storage.objects
  for select
  to anon, authenticated
  using (
    bucket_id = 'expert-files'
    and exists (
      select 1 from public.files f where f.storage_key = objects.name
    )
  );

-- ---------------------------------------------------------------------------
-- Чужой файл не прикрепляется к профилю
--
-- Внешний ключ проверяет существование, а не владение. Идентификатор фотографии
-- видимого профиля читается законно — он приходит в выдаче поиска, — поэтому без
-- этой проверки любой эксперт мог бы выставить у себя чужое лицо. Для платформы,
-- которая продаёт доверие к личности эксперта (§11), это дешёвая и обидная подделка.
--
-- security invoker: строка files читается под правами вызывающего. Свой файл он видит,
-- чужой — нет, и «не вижу» здесь означает «не владею», что для проверки владения
-- как раз верно. Администратор видит все файлы, но условие сравнивает владельца
-- с владельцем профиля, а не с самим собой, поэтому и он подменить не сможет.
-- ---------------------------------------------------------------------------

create or replace function public.assert_expert_files_owned()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.photo_file_id is not null and not exists (
    select 1 from public.files f
    where f.id = new.photo_file_id and f.owner_user_id = new.user_id
  ) then
    raise exception 'Photo file does not belong to this expert'
      using errcode = '42501';
  end if;

  if new.cv_file_id is not null and not exists (
    select 1 from public.files f
    where f.id = new.cv_file_id and f.owner_user_id = new.user_id
  ) then
    raise exception 'CV file does not belong to this expert'
      using errcode = '42501';
  end if;

  return new;
end;
$$;

create trigger experts_files_owned
  before insert or update of photo_file_id, cv_file_id on public.experts
  for each row
  execute function public.assert_expert_files_owned();

comment on function public.assert_expert_files_owned is
  'Не даёт прикрепить к профилю файл другого пользователя: внешний ключ проверяет '
  'существование, а не владение.';
